def get_year_stats(conn, year):
    cur = conn.cursor()
    cur.execute("SELECT inbox_count, sent_count, total_count, attachments_count FROM checkpoints_log WHERE year=?", (year,))
    row = cur.fetchone()
    if row:
        return row
    phase_label = f"Phase {int(year)-1396} ({year})" if int(year) > 1397 else "Phase 1 (1394-1397)"
    cur.execute("SELECT count(*) FROM emails WHERE phase=?", (phase_label,))
    tot = cur.fetchone()[0]
    cur.execute("SELECT count(*) FROM emails WHERE phase=? AND is_sent_by_me=1", (phase_label,))
    snt = cur.fetchone()[0]
    ibx = tot - snt
    cur.execute("""
        SELECT count(a.id) FROM attachments a
        JOIN emails e ON a.email_entry_id = e.entry_id
        WHERE e.phase=?
    """, (phase_label,))
    att = cur.fetchone()[0]
    return (ibx, snt, tot, att)

